export function demoQuestions(kind: ScenarioKind): Material['questions'] {
  const seeds =
    kind === 'bank' ? bank : kind === 'teachers' ? teachers : kind === 'security' ? security : [];
  return seeds.map(([text, options, correct_index, explanation, outcome], index) => ({
    id: `question-${index + 1}`,
    text,
    options,
    correct_index,
    explanation,
    outcome_ids: [`outcome-${outcome}`],
  }));
}
